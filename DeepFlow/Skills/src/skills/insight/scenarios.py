_ROLES = ("coach", "critic", "mirror", "observer")


def get_scenario_focus(input_context: Dict[str, Any], role: str) -> str:
    """
    根据 context 中的 decision_type 生成角色专属的场景聚焦提示。

    Args:
        input_context: 前端传入的 context（含 decision_type / scope）
        role: 角色键（coach/critic/mirror/observer）

    Returns:
        场景聚焦提示文本；未匹配模板或未知角色时返回空串（向后兼容）
    """
    if not isinstance(input_context, dict):
        return ""
    dtype = input_context.get("decision_type", "")
    if not dtype or dtype not in SCENARIOS:
        return ""
    if role not in _ROLES:
        return ""
    sc = SCENARIOS[dtype]
    header = f"场景模板：{sc['name']}"
    scope = input_context.get("scope", "")
    if scope:
        header += f"（范围：{scope}）"
    return f"\n{header}\n{sc[role]}\n"


def list_scenarios() -> Dict[str, str]:
    """返回可用模板清单（key -> 中文名），供前端展示与测试使用。"""
    return {k: v["name"] for k, v in SCENARIOS.items()}
